        for arq in (os.path.join(_ROBO_, "ROTEIRO-INSTALACAO.md"), os.path.join(_RAIZ_, "docs", "VISITA-KR-LAW.md")):
            with open(arq, encoding="utf-8") as f:
                t = f.read().lower()
            self.assertNotRegex(t, r"deslig\w* (a |o )?(defesa contra amea|antiv)", arq)
            self.assertIn("antivirus.html", t, arq)


